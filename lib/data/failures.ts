export function getFailuresByRunId(runId: string): FailureTrace[] {
  return failures.filter((f) => f.runId === runId);
}

export function getFailuresBySystemSlug(systemSlug: string): FailureTrace[] {
  const runPrefixMap: Record<string, string> = {
    mem0: "run_mem0_",
    letta: "run_letta_",
    zep: "run_zep_",
    mempalace: "run_mempalace_",
    mastra: "run_mastra_",
    byterover: "run_byterover_",
    omega: "run_omega_",
    memmachine: "run_memmachine_",
  };
  const prefix = runPrefixMap[systemSlug];
  if (!prefix) return [];

  return failures.filter((f) => f.runId.startsWith(prefix));
}
